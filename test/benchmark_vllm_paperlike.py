def validate_vllm_result(path: Path) -> tuple[dict[str, Any] | None, str]:
    if not path.is_file():
        return None, f"vLLM output JSON was not created: {path}"
    try:
        value = load_json(path)
    except (OSError, json.JSONDecodeError) as exc:
        return None, f"could not read vLLM output JSON: {exc}"
    if not isinstance(value, dict):
        return None, "vLLM output JSON root is not an object"
    missing = REQUIRED_VLLM_RESULT_KEYS.difference(value)
    if missing:
        return None, f"vLLM output JSON is missing fields: {', '.join(sorted(missing))}"
    try:
        elapsed = float(value["elapsed_time"])
        requests = int(value["num_requests"])
        float(value["requests_per_second"])
        float(value["tokens_per_second"])
    except (TypeError, ValueError) as exc:
        return None, f"vLLM output JSON contains invalid metric values: {exc}"
    if elapsed <= 0.0 or requests < 0:
        return None, "vLLM output JSON contains invalid elapsed_time or num_requests"
    return value, ""


def existing_run_is_successful(run_dir: Path) -> bool:
    metadata_path = run_dir / "metadata.json"
    result_path = run_dir / "vllm-result.json"
    if not metadata_path.is_file():
        return False
    try:
        metadata = load_json(metadata_path)
    except (OSError, json.JSONDecodeError):
        return False
    if not isinstance(metadata, dict) or metadata.get("status") != "ok":
        return False
    result, _ = validate_vllm_result(result_path)
    return result is not None


