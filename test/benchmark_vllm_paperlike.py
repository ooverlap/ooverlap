#!/usr/bin/env python3
"""
Run and summarize paper-like vLLM throughput experiments.

This replaces the repository's shell runner and separate summarizer with one
Python controller. Each benchmark is still executed in a fresh `vllm bench
throughput` subprocess so GPU memory and backend-specific environment variables
are isolated between runs.

Result files are written only below --out-dir. Model downloads and runtime
caches remain controlled by the environment generated by setup_env.sh, or by an
explicit --cache-root override.

Examples
--------
Use the environment file generated by setup_env.sh::

    python benchmark_vllm_paperlike.py \
      --runtime-env-file /local/tmp.USER/ooverlap_vllm_env.sh \
      --out-dir /project/results/vllm-paperlike \
      --models Qwen/Qwen2.5-7B-Instruct \
      --backends pynccl,ooverlap \
      --device-groups '0,1;0,1,2,3' \
      --batch-sizes 64,128,256 \
      --max-batched-tokens 4096,8192 \
      --workloads decode,prefill,mixed \
      --repetitions 3

Override only runtime/cache storage while keeping results elsewhere::

    python benchmark_vllm_paperlike.py \
      --cache-root /scratch/$USER/ooverlap-cache \
      --out-dir /project/results/vllm-paperlike

Add or override a workload with NAME:INPUT_LEN:OUTPUT_LEN::

    --workload long-prefill:4096:1

A JSON config file can provide the same matrix. CLI values override config
values when both are provided. Example schema::

    {
      "models": [
        {
          "name": "Qwen/Qwen2.5-7B-Instruct",
          "max_model_len": 2048,
          "gpu_memory_utilization": 0.85
        }
      ],
      "backends": ["pynccl", "ooverlap"],
      "baseline_backend": "pynccl",
      "device_groups": [[0, 1], [0, 1, 2, 3]],
      "batch_sizes": [64, 128],
      "max_batched_tokens": [4096],
      "workloads": [
        {"name": "decode", "input_len": 16, "output_len": 256},
        {"name": "prefill", "input_len": 1024, "output_len": 1}
      ],
      "repetitions": 2,
      "environment": {},
      "extra_vllm_args": []
    }
"""

