def execute_streaming(
    command: Sequence[str],
    environment: Mapping[str, str],
    log_path: Path,
    cwd: Path,
) -> tuple[int, float]:
    start = time.monotonic()
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8", buffering=1) as log_handle:
        process = subprocess.Popen(
            list(command),
            cwd=str(cwd),
            env=dict(environment),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            start_new_session=True,
        )
        try:
            assert process.stdout is not None
            for line in process.stdout:
                sys.stdout.write(line)
                sys.stdout.flush()
                log_handle.write(line)
            return_code = process.wait()
        except KeyboardInterrupt:
            # OOVERLAP_VLLM_PROCESS_GROUP_CLEANUP_V1
            # vLLM launches an engine process and multiple workers. Signalling
            # only the CLI parent can leave GPU-owning workers alive. Because
            # the child starts a new session, its PID is also its process-group
            # ID; signal the whole group and escalate only after timeouts.
            try:
                os.killpg(process.pid, signal.SIGINT)
            except ProcessLookupError:
                pass
            try:
                return_code = process.wait(timeout=20)
            except subprocess.TimeoutExpired:
                try:
                    os.killpg(process.pid, signal.SIGTERM)
                except ProcessLookupError:
                    pass
                try:
                    return_code = process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    try:
                        os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                    return_code = process.wait()
            raise
    return return_code, time.monotonic() - start


def normalized_record(metadata: Mapping[str, Any]) -> dict[str, Any]:
    spec = dict(metadata.get("spec", {}))
    result = metadata.get("result") if isinstance(metadata.get("result"), dict) else {}
    elapsed = float(result["elapsed_time"]) if "elapsed_time" in result else None
    num_requests = int(result["num_requests"]) if "num_requests" in result else None
    output_len = int(spec.get("output_len", 0) or 0)

    output_tokens_per_second: float | None = None
    if elapsed and elapsed > 0.0 and num_requests is not None:
        if "num_output_tokens" in result:
            try:
                output_tokens_per_second = float(result["num_output_tokens"]) / elapsed
            except (TypeError, ValueError):
                output_tokens_per_second = None
        if output_tokens_per_second is None:
            output_tokens_per_second = (num_requests * output_len) / elapsed

    return {
        **spec,
        "run_id": metadata.get("run_id"),
        "status": metadata.get("status"),
        "returncode": metadata.get("returncode"),
        "started_at": metadata.get("started_at"),
        "finished_at": metadata.get("finished_at"),
        "wall_time_s": metadata.get("wall_time_s"),
        "error": metadata.get("error", ""),
        "elapsed_s": elapsed,
        "num_requests": num_requests,
        "requests_per_s": (
            float(result["requests_per_second"])
            if "requests_per_second" in result
            else None
        ),
        "total_tokens_per_s": (
            float(result["tokens_per_second"])
            if "tokens_per_second" in result
            else None
        ),
        "output_tokens_per_s": output_tokens_per_second,
        "run_dir": metadata.get("run_dir"),
        "log_path": metadata.get("log_path"),
        "result_path": metadata.get("result_path"),
    }


def load_all_run_records(out_dir: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    runs_dir = out_dir / "runs"
    if not runs_dir.is_dir():
        return records
    for metadata_path in sorted(runs_dir.glob("*/metadata.json")):
        try:
            metadata = load_json(metadata_path)
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(metadata, dict):
            records.append(normalized_record(metadata))
    return records


