@dataclass(frozen=True)
class ModelSpec:
    name: str
    max_model_len: int
    gpu_memory_utilization: float


@dataclass(frozen=True)
class WorkloadSpec:
    name: str
    input_len: int
    output_len: int


@dataclass(frozen=True)
class RunSpec:
    model: str
    max_model_len: int
    gpu_memory_utilization: float
    backend: str
    baseline_backend: str
    devices: tuple[int, ...]
    tensor_parallel_size: int
    workload: str
    input_len: int
    output_len: int
    max_num_seqs: int
    max_num_batched_tokens: int
    num_prompts: int
    num_warmups: int
    repetition: int
    dataset_name: str
    random_range_ratio: float
    seed: int
    enforce_eager: bool
    disable_detokenize: bool
    trust_remote_code: bool
    dtype: str

    def comparison_key(self) -> tuple[Any, ...]:
        """Configuration key excluding backend, preserving paired repetitions."""
        return (
            self.model,
            self.max_model_len,
            self.gpu_memory_utilization,
            self.devices,
            self.tensor_parallel_size,
            self.workload,
            self.input_len,
            self.output_len,
            self.max_num_seqs,
            self.max_num_batched_tokens,
            self.num_prompts,
            self.num_warmups,
            self.repetition,
            self.dataset_name,
            self.random_range_ratio,
            self.seed,
            self.enforce_eager,
            self.disable_detokenize,
            self.trust_remote_code,
            self.dtype,
        )

    def aggregate_key(self) -> tuple[Any, ...]:
        """Configuration key excluding backend and repetition."""
        key = list(self.comparison_key())
        # repetition is the 12th field in comparison_key.
        del key[12]
        return tuple(key)


class ConfigurationError(ValueError):
    pass


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def atomic_write_json(path: Path, value: Any) -> None:
    atomic_write_text(path, json.dumps(value, indent=2, sort_keys=True) + "\n")


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def parse_csv_strings(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def parse_csv_ints(value: str, option: str) -> list[int]:
    try:
        values = [int(item.strip()) for item in value.split(",") if item.strip()]
    except ValueError as exc:
        raise ConfigurationError(f"{option} must be a comma-separated integer list") from exc
    if not values:
        raise ConfigurationError(f"{option} must not be empty")
    return values


def parse_device_group_text(value: str) -> list[list[int]]:
    groups: list[list[int]] = []
    for group_text in value.split(";"):
        if not group_text.strip():
            continue
        group = parse_csv_ints(group_text, "--device-groups")
        validate_device_group(group)
        groups.append(group)
    if not groups:
        raise ConfigurationError("--device-groups must contain at least one group")
    return groups


def validate_device_group(group: Sequence[int]) -> None:
    if len(group) < 1:
        raise ConfigurationError("device groups must contain at least one CUDA device")
    if len(set(group)) != len(group):
        raise ConfigurationError(f"device group contains duplicates: {list(group)}")
    if any(device < 0 for device in group):
        raise ConfigurationError(f"device ids must be non-negative: {list(group)}")


def parse_workload_text(value: str) -> WorkloadSpec:
    pieces = value.split(":")
    if len(pieces) != 3:
        raise ConfigurationError(
            f"invalid workload {value!r}; expected NAME:INPUT_LEN:OUTPUT_LEN"
        )
    name = pieces[0].strip()
    if not name:
        raise ConfigurationError("workload name must not be empty")
    try:
        input_len = int(pieces[1])
        output_len = int(pieces[2])
    except ValueError as exc:
        raise ConfigurationError(
            f"invalid workload {value!r}; lengths must be integers"
        ) from exc
    if input_len <= 0 or output_len <= 0:
        raise ConfigurationError("workload input/output lengths must be positive")
    return WorkloadSpec(name=name, input_len=input_len, output_len=output_len)


def parse_env_assignments(values: Sequence[str]) -> dict[str, str]:
    result: dict[str, str] = {}
    for value in values:
        if "=" not in value:
            raise ConfigurationError(f"invalid --env value {value!r}; expected KEY=VALUE")
        key, item = value.split("=", 1)
        key = key.strip()
        if not key:
            raise ConfigurationError("--env key must not be empty")
        result[key] = item
    return result


def load_optional_config(path: str | None) -> dict[str, Any]:
    if not path:
        return {}
    config_path = Path(path).expanduser().resolve()
    if not config_path.is_file():
        raise ConfigurationError(f"config file does not exist: {config_path}")
    value = load_json(config_path)
    if not isinstance(value, dict):
        raise ConfigurationError("config root must be a JSON object")
    return value


def selected(cli_value: Any, config: Mapping[str, Any], key: str, default: Any) -> Any:
    if cli_value is not None:
        return cli_value
    if key in config:
        return config[key]
    return default


def normalize_models(
    raw_models: Any,
    global_max_model_len: int | None,
    global_gpu_memory_utilization: float | None,
) -> list[ModelSpec]:
    if isinstance(raw_models, str):
        entries: list[Any] = parse_csv_strings(raw_models)
    elif isinstance(raw_models, list):
        entries = raw_models
    else:
        raise ConfigurationError("models must be a list or comma-separated string")

    models: list[ModelSpec] = []
    for entry in entries:
        if isinstance(entry, str):
            name = entry
            entry_max_len = 2048
            entry_gpu_util = 0.85
        elif isinstance(entry, dict):
            name = str(entry.get("name", "")).strip()
            entry_max_len = int(entry.get("max_model_len", 2048))
            entry_gpu_util = float(entry.get("gpu_memory_utilization", 0.85))
        else:
            raise ConfigurationError("each model must be a string or JSON object")

        if not name:
            raise ConfigurationError("model name must not be empty")
        max_len = global_max_model_len if global_max_model_len is not None else entry_max_len
        gpu_util = (
            global_gpu_memory_utilization
            if global_gpu_memory_utilization is not None
            else entry_gpu_util
        )
        if max_len <= 0:
            raise ConfigurationError("max_model_len must be positive")
        if not 0.0 < gpu_util <= 1.0:
            raise ConfigurationError("gpu_memory_utilization must be in (0, 1]")
        models.append(
            ModelSpec(
                name=name,
                max_model_len=int(max_len),
                gpu_memory_utilization=float(gpu_util),
            )
        )

    if not models:
        raise ConfigurationError("at least one model is required")
    return models


def normalize_workloads(
    raw_workloads: Any,
    custom_workloads: Sequence[str],
) -> list[WorkloadSpec]:
    by_name: dict[str, WorkloadSpec] = {}

    if isinstance(raw_workloads, str):
        entries: list[Any] = parse_csv_strings(raw_workloads)
    elif isinstance(raw_workloads, list):
        entries = raw_workloads
    else:
        raise ConfigurationError("workloads must be a list or comma-separated string")

    for entry in entries:
        if isinstance(entry, str):
            if entry not in DEFAULT_WORKLOADS:
                raise ConfigurationError(
                    f"unknown built-in workload {entry!r}; use --workload NAME:IN:OUT"
                )
            raw = DEFAULT_WORKLOADS[entry]
            workload = WorkloadSpec(**raw)
        elif isinstance(entry, dict):
            try:
                workload = WorkloadSpec(
                    name=str(entry["name"]),
                    input_len=int(entry["input_len"]),
                    output_len=int(entry["output_len"]),
                )
            except (KeyError, TypeError, ValueError) as exc:
                raise ConfigurationError(f"invalid workload object: {entry!r}") from exc
            if not workload.name or workload.input_len <= 0 or workload.output_len <= 0:
                raise ConfigurationError(f"invalid workload object: {entry!r}")
        else:
            raise ConfigurationError("each workload must be a name or JSON object")
        by_name[workload.name] = workload

    for value in custom_workloads:
        workload = parse_workload_text(value)
        by_name[workload.name] = workload

    if not by_name:
        raise ConfigurationError("at least one workload is required")
    return list(by_name.values())


def normalize_device_groups(raw: Any) -> list[list[int]]:
    if isinstance(raw, str):
        return parse_device_group_text(raw)
    if not isinstance(raw, list):
        raise ConfigurationError("device_groups must be a list or semicolon-separated string")

    groups: list[list[int]] = []
    for item in raw:
        if isinstance(item, str):
            group = parse_csv_ints(item, "device_groups")
        elif isinstance(item, list):
            group = [int(value) for value in item]
        else:
            raise ConfigurationError("each device group must be a list or comma-separated string")
        validate_device_group(group)
        groups.append(group)
    if not groups:
        raise ConfigurationError("at least one device group is required")
    return groups


def normalize_int_list(raw: Any, name: str, minimum: int = 1) -> list[int]:
    if isinstance(raw, str):
        values = parse_csv_ints(raw, name)
    elif isinstance(raw, list):
        try:
            values = [int(value) for value in raw]
        except (TypeError, ValueError) as exc:
            raise ConfigurationError(f"{name} must contain integers") from exc
    else:
        raise ConfigurationError(f"{name} must be a list or comma-separated string")
    if not values or any(value < minimum for value in values):
        raise ConfigurationError(f"{name} values must be >= {minimum}")
    return values


def shell_environment_from_file(path: Path, inherited: Mapping[str, str]) -> dict[str, str]:
    if not path.is_file():
        raise ConfigurationError(f"runtime environment file does not exist: {path}")

    command = [
        "bash",
        "-lc",
        'set -e; source "$1" >/dev/null; env -0',
        "ooverlap-runtime-env",
        str(path),
    ]
    process = subprocess.run(
        command,
        env=dict(inherited),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if process.returncode != 0:
        error = process.stderr.decode("utf-8", errors="replace")
        raise ConfigurationError(
            f"failed to source runtime environment file {path}:\n{error}"
        )

    environment: dict[str, str] = {}
    for item in process.stdout.split(b"\0"):
        if not item or b"=" not in item:
            continue
        key, value = item.split(b"=", 1)
        environment[key.decode("utf-8", errors="surrogateescape")] = value.decode(
            "utf-8", errors="surrogateescape"
        )
    if not environment:
        raise ConfigurationError(f"runtime environment file produced no environment: {path}")
    return environment


def apply_cache_root(environment: dict[str, str], root: Path) -> dict[str, str]:
    root = root.expanduser().resolve()
    paths = {
        "TMPDIR": root / "tmp",
        "UV_CACHE_DIR": root / "uv-cache",
        "PIP_CACHE_DIR": root / "pip-cache",
        "TORCH_EXTENSIONS_DIR": root / "torch-extensions",
        "XDG_CACHE_HOME": root / "xdg-cache",
        "XDG_CONFIG_HOME": root / "xdg-config",
        "HF_HOME": root / "hf-cache",
        "HF_HUB_CACHE": root / "hf-cache" / "hub",
        "TRANSFORMERS_CACHE": root / "hf-cache" / "transformers",
        "VLLM_CACHE_ROOT": root / "vllm-cache",
        "VLLM_CONFIG_ROOT": root / "vllm-config",
        "FETCHCONTENT_BASE_DIR": root / "vllm-deps",
    }
    for path in paths.values():
        path.mkdir(parents=True, exist_ok=True)
    updated = dict(environment)
    updated["OOTMP"] = str(root)
    for key, path in paths.items():
        updated[key] = str(path)
    return updated


def resolved_path(value: str) -> Path:
    return Path(value).expanduser().resolve(strict=False)


def paths_overlap(first: Path, second: Path) -> bool:
    return first == second or first in second.parents or second in first.parents


def validate_result_cache_separation(out_dir: Path, environment: Mapping[str, str]) -> None:
    out_dir = out_dir.resolve(strict=False)
    conflicts: list[tuple[str, Path]] = []
    for key in CACHE_PATH_KEYS:
        value = environment.get(key, "").strip()
        if not value:
            continue
        cache_path = resolved_path(value)
        if paths_overlap(out_dir, cache_path):
            conflicts.append((key, cache_path))
    if conflicts:
        details = "\n".join(f"  {key}={path}" for key, path in conflicts)
        raise ConfigurationError(
            "--out-dir overlaps a runtime/cache directory. Results and caches must "
            f"be separate.\nout_dir={out_dir}\nconflicts:\n{details}"
        )


def slugify(value: str, limit: int = 48) -> str:
    pieces: list[str] = []
    previous_dash = False
    for char in value.lower():
        if char.isalnum():
            pieces.append(char)
            previous_dash = False
        elif not previous_dash:
            pieces.append("-")
            previous_dash = True
    slug = "".join(pieces).strip("-") or "item"
    return slug[:limit].rstrip("-")


def canonical_hash(value: Any, length: int = 10) -> str:
    data = json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(data).hexdigest()[:length]


def run_id(spec: RunSpec) -> str:
    readable_model = slugify(spec.model)
    readable_workload = slugify(spec.workload, limit=24)
    device_text = "-".join(str(device) for device in spec.devices)
    payload = asdict(spec)
    return (
        f"{readable_model}__tp{spec.tensor_parallel_size}__dev{device_text}__"
        f"{slugify(spec.backend, 20)}__{readable_workload}__"
        f"in{spec.input_len}__out{spec.output_len}__bs{spec.max_num_seqs}__"
        f"mbt{spec.max_num_batched_tokens}__r{spec.repetition}__"
        f"{canonical_hash(payload)}"
    )


def build_run_specs(
    models: Sequence[ModelSpec],
    workloads: Sequence[WorkloadSpec],
    backends: Sequence[str],
    baseline_backend: str,
    device_groups: Sequence[Sequence[int]],
    batch_sizes: Sequence[int],
    max_batched_tokens: Sequence[int],
    repetitions: int,
    prompt_multiplier: int,
    exact_num_prompts: int | None,
    exact_num_warmups: int | None,
    dataset_name: str,
    random_range_ratio: float,
    seed: int,
    enforce_eager: bool,
    disable_detokenize: bool,
    trust_remote_code: bool,
    dtype: str,
) -> list[RunSpec]:
    specs: list[RunSpec] = []
    for model in models:
        for devices in device_groups:
            devices_tuple = tuple(int(device) for device in devices)
            for workload in workloads:
                for batch_size in batch_sizes:
                    num_prompts = (
                        exact_num_prompts
                        if exact_num_prompts is not None
                        else batch_size * prompt_multiplier
                    )
                    num_warmups = (
                        exact_num_warmups
                        if exact_num_warmups is not None
                        else batch_size
                    )
                    for token_limit in max_batched_tokens:
                        for repetition in range(repetitions):
                            # Keep backends adjacent to reduce machine/time drift.
                            for backend in backends:
                                specs.append(
                                    RunSpec(
                                        model=model.name,
                                        max_model_len=model.max_model_len,
                                        gpu_memory_utilization=model.gpu_memory_utilization,
                                        backend=backend,
                                        baseline_backend=baseline_backend,
                                        devices=devices_tuple,
                                        tensor_parallel_size=len(devices_tuple),
                                        workload=workload.name,
                                        input_len=workload.input_len,
                                        output_len=workload.output_len,
                                        max_num_seqs=batch_size,
                                        max_num_batched_tokens=token_limit,
                                        num_prompts=num_prompts,
                                        num_warmups=num_warmups,
                                        repetition=repetition,
                                        dataset_name=dataset_name,
                                        random_range_ratio=random_range_ratio,
                                        seed=seed,
                                        enforce_eager=enforce_eager,
                                        disable_detokenize=disable_detokenize,
                                        trust_remote_code=trust_remote_code,
                                        dtype=dtype,
                                    )
                                )
    return specs


def resolve_executable(value: str | None, environment: Mapping[str, str]) -> str:
    if value:
        candidate = Path(value).expanduser()
        if candidate.parent != Path(".") or "/" in value:
            candidate = candidate.resolve()
            if not candidate.is_file() or not os.access(candidate, os.X_OK):
                raise ConfigurationError(f"vLLM executable is not executable: {candidate}")
            return str(candidate)
        found = shutil.which(value, path=environment.get("PATH"))
    else:
        found = shutil.which("vllm", path=environment.get("PATH"))
    if not found:
        raise ConfigurationError(
            "could not find the vllm executable. Source setup_env.sh's runtime "
            "environment or pass --runtime-env-file/--vllm-executable."
        )
    return found


def command_for_run(
    executable: str,
    spec: RunSpec,
    output_json: Path,
    extra_vllm_args: Sequence[str],
) -> list[str]:
    command = [
        executable,
        "bench",
        "throughput",
        "--backend",
        "vllm",
        "--model",
        spec.model,
        "--dataset-name",
        spec.dataset_name,
        "--random-range-ratio",
        str(spec.random_range_ratio),
        "--tensor-parallel-size",
        str(spec.tensor_parallel_size),
        "--max-model-len",
        str(spec.max_model_len),
        "--gpu-memory-utilization",
        str(spec.gpu_memory_utilization),
        "--seed",
        str(spec.seed),
        "--random-input-len",
        str(spec.input_len),
        "--random-output-len",
        str(spec.output_len),
        "--num-prompts",
        str(spec.num_prompts),
        "--num-warmups",
        str(spec.num_warmups),
        "--max-num-seqs",
        str(spec.max_num_seqs),
        "--max-num-batched-tokens",
        str(spec.max_num_batched_tokens),
        "--output-json",
        str(output_json),
    ]
    if spec.enforce_eager:
        command.append("--enforce-eager")
    if spec.disable_detokenize:
        command.append("--disable-detokenize")
    if spec.trust_remote_code:
        command.append("--trust-remote-code")
    if spec.dtype:
        command.extend(["--dtype", spec.dtype])
    command.extend(extra_vllm_args)
    return command


def run_environment(
    base_environment: Mapping[str, str],
    spec: RunSpec,
    flashinfer_sampler: str,
    ooverlap_debug: str,
    rr_dtype: str,
    rr_slots: int,
    rr_capacity_bytes: int,
    explicit_environment: Mapping[str, str],
) -> dict[str, str]:
    environment = dict(base_environment)
    environment.update(explicit_environment)
    environment["CUDA_VISIBLE_DEVICES"] = ",".join(str(device) for device in spec.devices)
    environment["VLLM_FORCE_ALLREDUCE_BACKEND"] = spec.backend
    environment["VLLM_USE_FLASHINFER_SAMPLER"] = flashinfer_sampler
    environment["VLLM_OOVERLAP_DEBUG"] = ooverlap_debug
    environment["VLLM_OOVERLAP_RR_DTYPE"] = rr_dtype
    environment["VLLM_OOVERLAP_RR_SLOTS"] = str(rr_slots)
    environment["VLLM_OOVERLAP_RR_CAPACITY_BYTES"] = str(rr_capacity_bytes)
    environment.pop("VLLM_OOVERLAP_BROKER_KEY", None)
    return environment


