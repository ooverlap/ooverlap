def aggregate_key_from_record(record: Mapping[str, Any]) -> tuple[Any, ...]:
    key = list(comparison_key_from_record(record))
    del key[12]
    return tuple(key)


def add_baseline_metrics(
    records: Sequence[dict[str, Any]], baseline_backend: str
) -> list[dict[str, Any]]:
    baseline_by_key: dict[tuple[Any, ...], dict[str, Any]] = {}
    for record in records:
        if record.get("status") != "ok":
            continue
        if record.get("backend") == baseline_backend:
            baseline_by_key[comparison_key_from_record(record)] = record

    rows: list[dict[str, Any]] = []
    for record in records:
        row = dict(record)
        row["baseline_backend"] = baseline_backend
        row["speedup_vs_base"] = None
        row["change_vs_base_pct"] = None
        if record.get("status") == "ok" and record.get("elapsed_s"):
            baseline = baseline_by_key.get(comparison_key_from_record(record))
            if baseline and baseline.get("elapsed_s"):
                speedup = float(baseline["elapsed_s"]) / float(record["elapsed_s"])
                row["speedup_vs_base"] = speedup
                row["change_vs_base_pct"] = (speedup - 1.0) * 100.0
        rows.append(row)
    return rows


def csv_safe(value: Any) -> Any:
    if isinstance(value, (list, tuple, dict)):
        return json.dumps(value, sort_keys=True)
    return value


def write_csv(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    if not rows:
        atomic_write_text(path, "")
        return
    fieldnames: list[str] = []
    seen: set[str] = set()
    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                fieldnames.append(key)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.parent.mkdir(parents=True, exist_ok=True)
    with temporary.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: csv_safe(row.get(key)) for key in fieldnames})
    temporary.replace(path)


def mean_or_none(values: Iterable[Any]) -> float | None:
    converted = [float(value) for value in values if value is not None]
    return statistics.mean(converted) if converted else None


def pstdev_or_zero(values: Iterable[Any]) -> float:
    converted = [float(value) for value in values if value is not None]
    return statistics.pstdev(converted) if len(converted) > 1 else 0.0


def aggregate_rows(rows: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[tuple[Any, ...], list[dict[str, Any]]] = {}
    for row in rows:
        if row.get("status") != "ok":
            continue
        key = aggregate_key_from_record(row) + (row.get("backend"),)
        grouped.setdefault(key, []).append(row)

    aggregates: list[dict[str, Any]] = []
    for group_rows in grouped.values():
        first = group_rows[0]
        elapsed_values = [row.get("elapsed_s") for row in group_rows]
        request_values = [row.get("requests_per_s") for row in group_rows]
        total_token_values = [row.get("total_tokens_per_s") for row in group_rows]
        output_token_values = [row.get("output_tokens_per_s") for row in group_rows]
        speedup_values = [row.get("speedup_vs_base") for row in group_rows]
        aggregates.append(
            {
                "model": first.get("model"),
                "backend": first.get("backend"),
                "baseline_backend": first.get("baseline_backend"),
                "devices": first.get("devices"),
                "tensor_parallel_size": first.get("tensor_parallel_size"),
                "workload": first.get("workload"),
                "input_len": first.get("input_len"),
                "output_len": first.get("output_len"),
                "max_num_seqs": first.get("max_num_seqs"),
                "max_num_batched_tokens": first.get("max_num_batched_tokens"),
                "num_prompts": first.get("num_prompts"),
                "num_warmups": first.get("num_warmups"),
                "max_model_len": first.get("max_model_len"),
                "gpu_memory_utilization": first.get("gpu_memory_utilization"),
                "repetitions_ok": len(group_rows),
                "elapsed_mean_s": mean_or_none(elapsed_values),
                "elapsed_std_s": pstdev_or_zero(elapsed_values),
                "requests_per_s_mean": mean_or_none(request_values),
                "total_tokens_per_s_mean": mean_or_none(total_token_values),
                "output_tokens_per_s_mean": mean_or_none(output_token_values),
                "speedup_vs_base_mean": mean_or_none(speedup_values),
                "change_vs_base_pct_mean": (
                    None
                    if mean_or_none(speedup_values) is None
                    else (float(mean_or_none(speedup_values)) - 1.0) * 100.0
                ),
            }
        )

    aggregates.sort(
        key=lambda row: (
            str(row.get("model")),
            int(row.get("tensor_parallel_size") or 0),
            str(row.get("workload")),
            int(row.get("max_num_seqs") or 0),
            int(row.get("max_num_batched_tokens") or 0),
            str(row.get("backend")),
        )
    )
    return aggregates


def format_optional(value: Any, format_spec: str) -> str:
    if value is None:
        return "N/A"
    return format(float(value), format_spec)


def make_summary_text(
    rows: Sequence[dict[str, Any]],
    aggregates: Sequence[dict[str, Any]],
    baseline_backend: str,
) -> str:
    lines = [
        "vLLM paper-like throughput summary",
        f"Generated: {utc_now()}",
        f"Baseline backend: {baseline_backend}",
        "",
    ]

    grouped: dict[tuple[Any, ...], list[dict[str, Any]]] = {}
    for row in aggregates:
        key = (
            row.get("model"),
            tuple(row.get("devices", [])),
            row.get("tensor_parallel_size"),
            row.get("workload"),
            row.get("input_len"),
            row.get("output_len"),
            row.get("max_num_seqs"),
            row.get("max_num_batched_tokens"),
        )
        grouped.setdefault(key, []).append(row)

    for key in sorted(grouped, key=lambda value: tuple(str(item) for item in value)):
        model, devices, tp, workload, input_len, output_len, batch, token_limit = key
        lines.extend(
            [
                "=" * 88,
                f"Model: {model}",
                f"Devices: {','.join(str(device) for device in devices)}  TP: {tp}",
                f"Workload: {workload}  input={input_len}  output={output_len}",
                f"max_num_seqs={batch}  max_num_batched_tokens={token_limit}",
                "-" * 88,
            ]
        )
        group_rows = sorted(
            grouped[key],
            key=lambda row: (
                row.get("backend") != baseline_backend,
                str(row.get("backend")),
            ),
        )
        for row in group_rows:
            marker = " [base]" if row.get("backend") == baseline_backend else ""
            lines.append(
                f"{str(row.get('backend')):<16} "
                f"reps={int(row.get('repetitions_ok') or 0):<3d} "
                f"elapsed={format_optional(row.get('elapsed_mean_s'), '.4f')}s "
                f"std={format_optional(row.get('elapsed_std_s'), '.4f')}s "
                f"req/s={format_optional(row.get('requests_per_s_mean'), '.2f')} "
                f"out_tok/s={format_optional(row.get('output_tokens_per_s_mean'), '.1f')} "
                f"speedup={format_optional(row.get('speedup_vs_base_mean'), '.4f')}x "
                f"delta={format_optional(row.get('change_vs_base_pct_mean'), '+.2f')}%"
                f"{marker}"
            )
        lines.append("")

    failures = [row for row in rows if row.get("status") != "ok"]
    if failures:
        lines.extend(["=" * 88, "Failed or incomplete runs:"])
        for row in failures:
            lines.append(
                f"- {row.get('run_id')}: returncode={row.get('returncode')} "
                f"error={row.get('error', '')}"
            )
        lines.append("")

    if not aggregates:
        lines.append("No successful benchmark results were found.")

    return "\n".join(lines).rstrip() + "\n"


def rebuild_summaries(out_dir: Path, baseline_backend: str) -> tuple[int, int]:
    records = load_all_run_records(out_dir)
    rows = add_baseline_metrics(records, baseline_backend)
    rows.sort(
        key=lambda row: (
            str(row.get("model")),
            int(row.get("tensor_parallel_size") or 0),
            str(row.get("workload")),
            int(row.get("max_num_seqs") or 0),
            int(row.get("max_num_batched_tokens") or 0),
            int(row.get("repetition") or 0),
            str(row.get("backend")),
        )
    )

    jsonl = "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows)
    atomic_write_text(out_dir / "runs.jsonl", jsonl)
    write_csv(out_dir / "summary.csv", rows)

    aggregates = aggregate_rows(rows)
    write_csv(out_dir / "summary_aggregate.csv", aggregates)
    atomic_write_text(
        out_dir / "summary.txt",
        make_summary_text(rows, aggregates, baseline_backend),
    )
    return len(rows), len(aggregates)


def current_git_commit(cwd: Path) -> str:
    try:
        process = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(cwd),
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=False,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return process.stdout.strip() if process.returncode == 0 else ""


def executable_version(executable: str, environment: Mapping[str, str]) -> str:
    try:
        process = subprocess.run(
            [executable, "--version"],
            env=dict(environment),
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"unavailable: {exc}"
    output = process.stdout.strip()
    return output if output else f"returncode={process.returncode}"


def validate_preflight(
    backends: Sequence[str],
    environment: Mapping[str, str],
    skip_preflight: bool,
) -> list[str]:
    warnings: list[str] = []
    if "ooverlap" in backends:
        extension = environment.get("VLLM_OOVERLAP_TORCH_EXT", "").strip()
        if not extension:
            message = (
                "VLLM_OOVERLAP_TORCH_EXT is not set although the ooverlap backend "
                "was requested"
            )
            if skip_preflight:
                warnings.append(message)
            else:
                raise ConfigurationError(message)
        elif not Path(extension).expanduser().is_file():
            message = f"VLLM_OOVERLAP_TORCH_EXT does not exist: {extension}"
            if skip_preflight:
                warnings.append(message)
            else:
                raise ConfigurationError(message)

    missing_cache_keys = [
        key
        for key in ("HF_HOME", "VLLM_CACHE_ROOT", "TORCH_EXTENSIONS_DIR")
        if not environment.get(key)
    ]
    if missing_cache_keys:
        warnings.append(
            "cache variables are not set and library defaults will be used: "
            + ", ".join(missing_cache_keys)
        )
    return warnings


